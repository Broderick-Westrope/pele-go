// Writes internal/svg/unicode.go: the code point ranges V8 matches with \p{L} and \p{N}, for
// the font-name check upstream does with those classes. Go's unicode package is often an
// older Unicode version than V8's, so the tables come from the Node that runs the oracle.
//
// Usage: node scripts/gen-unicode-props.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

function ranges(re) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const ok = c < 0x110000 && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c;
    if (!ok && start >= 0) {
      out.push([start, c - 1]);
      start = -1;
    }
  }
  return out;
}

const table = (name, rs) =>
  `var ${name} = []span{\n` + rs.map(([a, b]) => `\t{0x${a.toString(16)}, 0x${b.toString(16)}},`).join('\n') + '\n}\n';

const go = `// Code generated by scripts/gen-unicode-props.mjs with Node ${process.version} (Unicode ${process.versions.unicode}); DO NOT EDIT.

package svg

// unicodeVersion is the Unicode version of the tables, which is V8's in the Node that wrote them.
const unicodeVersion = "${process.versions.unicode}"

${table('letters', ranges(/\p{L}/u))}
${table('numbers', ranges(/\p{N}/u))}`;

writeFileSync(fileURLToPath(new URL('../internal/svg/unicode.go', import.meta.url)), go);
